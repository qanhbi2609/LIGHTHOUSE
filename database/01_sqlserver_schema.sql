/* LIGHTHOUSE SQL SERVER DATABASE – 16 tables from SDD, adapted for operational consistency.
   IMPORTANT: This script prepares the designed SQL schema; the bundled Node demo runs on JSON.
   Use SSMS; run on a new EMPTY development database only. */
IF DB_ID('LighthouseDB') IS NULL CREATE DATABASE LighthouseDB;
GO
USE LighthouseDB;
GO
CREATE TABLE Quyen (
  maQuyen VARCHAR(20) NOT NULL PRIMARY KEY,
  tenQuyen NVARCHAR(100) NOT NULL
);
GO
CREATE TABLE NguoiDung (
  maNguoiDung VARCHAR(20) NOT NULL PRIMARY KEY,
  hoTen NVARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  matKhau VARCHAR(255) NOT NULL, -- salted password hash; never plaintext
  vaiTro NVARCHAR(50) NOT NULL,
  dangHoatDong BIT NOT NULL DEFAULT(1)
);
GO
CREATE TABLE ChiTietQuyen (
  maNguoiDung VARCHAR(20) NOT NULL,
  maQuyen VARCHAR(20) NOT NULL,
  CONSTRAINT PK_ChiTietQuyen PRIMARY KEY(maNguoiDung,maQuyen),
  CONSTRAINT FK_CTQ_ND FOREIGN KEY(maNguoiDung) REFERENCES NguoiDung(maNguoiDung),
  CONSTRAINT FK_CTQ_Q FOREIGN KEY(maQuyen) REFERENCES Quyen(maQuyen)
);
GO
CREATE TABLE LichSuHoatDong (
  maLichSu VARCHAR(20) NOT NULL PRIMARY KEY,
  maNguoiDung VARCHAR(20) NOT NULL,
  hoatDong NVARCHAR(200) NOT NULL,
  doiTuong NVARCHAR(100) NOT NULL,
  thoiGian DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT FK_LS_ND FOREIGN KEY(maNguoiDung) REFERENCES NguoiDung(maNguoiDung)
);
GO
CREATE TABLE HoSoDangKy (
  maHoSo VARCHAR(20) NOT NULL PRIMARY KEY,
  ngayDangKy DATE NOT NULL DEFAULT CAST(GETDATE() AS DATE),
  hoTen NVARCHAR(100) NOT NULL,
  ngaySinh DATE NULL,
  queQuan NVARCHAR(100) NULL,
  diaChiThuongTru NVARCHAR(200) NULL,
  soDienThoai VARCHAR(10) NOT NULL,
  email VARCHAR(100) NOT NULL,
  CCCD VARCHAR(12) NULL,
  hoanCanhGiaDinh NVARCHAR(500) NULL,
  truongHoc NVARCHAR(150) NOT NULL,
  nganhHoc NVARCHAR(100) NOT NULL,
  moTaNganhHoc NVARCHAR(500) NULL,
  trangThaiHoSo NVARCHAR(50) NOT NULL DEFAULT N'Chờ kiểm tra',
  ghiChuXuLy NVARCHAR(1000) NULL,
  CONSTRAINT CK_HSDK_Phone CHECK (LEN(soDienThoai)=10 AND soDienThoai NOT LIKE '%[^0-9]%'),
  CONSTRAINT CK_HSDK_Status CHECK (trangThaiHoSo IN (N'Chờ kiểm tra',N'Đạt yêu cầu',N'Chờ bổ sung',N'Từ chối',N'Đã tiếp nhận'))
);
GO
CREATE TABLE GiayToMinhChung (
  maGiayTo VARCHAR(20) NOT NULL PRIMARY KEY,
  maHoSo VARCHAR(20) NOT NULL,
  tenGiayTo NVARCHAR(150) NOT NULL,
  linkGiayTo NVARCHAR(500) NOT NULL,
  CONSTRAINT FK_GT_HS FOREIGN KEY(maHoSo) REFERENCES HoSoDangKy(maHoSo)
);
GO
CREATE TABLE Phong (
  maPhong VARCHAR(20) NOT NULL PRIMARY KEY,
  sucChua INT NOT NULL CHECK (sucChua > 0),
  trangThaiPhong NVARCHAR(50) NOT NULL DEFAULT N'Trống'
);
GO
CREATE TABLE SinhVien (
  maQuanLy VARCHAR(20) NOT NULL PRIMARY KEY,
  maHoSo VARCHAR(20) NOT NULL UNIQUE,
  maNguoiDung VARCHAR(20) NULL UNIQUE,
  maPhong VARCHAR(20) NULL, -- NULL is required for 'Chưa bố trí'
  ngayTiepNhan DATE NOT NULL,
  hoTen NVARCHAR(100) NOT NULL,
  ngaySinh DATE NULL,
  queQuan NVARCHAR(100) NULL,
  diaChiThuongTru NVARCHAR(200) NULL,
  soDienThoai VARCHAR(10) NULL,
  email VARCHAR(100) NOT NULL,
  CCCD VARCHAR(12) NULL,
  hoanCanhGiaDinh NVARCHAR(500) NULL,
  truongHoc NVARCHAR(150) NOT NULL,
  nganhHoc NVARCHAR(100) NOT NULL,
  nienKhoa VARCHAR(20) NULL,
  maSinhVien VARCHAR(25) NULL,
  trangThaiHoTro NVARCHAR(50) NOT NULL DEFAULT N'Đang hỗ trợ',
  ngayKetThuc DATE NULL,
  lyDoKetThuc NVARCHAR(500) NULL,
  CONSTRAINT FK_SV_HS FOREIGN KEY(maHoSo) REFERENCES HoSoDangKy(maHoSo),
  CONSTRAINT FK_SV_ND FOREIGN KEY(maNguoiDung) REFERENCES NguoiDung(maNguoiDung),
  CONSTRAINT FK_SV_Phong FOREIGN KEY(maPhong) REFERENCES Phong(maPhong)
);
GO
CREATE TABLE HinhAnh (
  maHinhAnh VARCHAR(20) NOT NULL PRIMARY KEY,
  maQuanLy VARCHAR(20) NOT NULL,
  thoiGian DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  linkHinhAnh NVARCHAR(500) NOT NULL,
  CONSTRAINT FK_HA_SV FOREIGN KEY(maQuanLy) REFERENCES SinhVien(maQuanLy)
);
GO
CREATE TABLE KetQuaHocTap (
  maKetQua VARCHAR(20) NOT NULL PRIMARY KEY,
  maQuanLy VARCHAR(20) NOT NULL,
  ngayGui DATE NOT NULL,
  hocKy VARCHAR(10) NOT NULL,
  namHoc VARCHAR(9) NOT NULL,
  gpa DECIMAL(4,2) NOT NULL CHECK(gpa BETWEEN 0 AND 4),
  xepLoai NVARCHAR(30) NULL,
  soMonNo INT NOT NULL DEFAULT 0 CHECK(soMonNo>=0),
  chungChi NVARCHAR(200) NULL,
  minhChungKQHT NVARCHAR(500) NULL,
  noiDungBoSung NVARCHAR(500) NULL,
  trangThaiDuyet NVARCHAR(50) NOT NULL DEFAULT N'Chờ xét duyệt',
  CONSTRAINT FK_KQ_SV FOREIGN KEY(maQuanLy) REFERENCES SinhVien(maQuanLy)
);
GO
CREATE TABLE MucTieu (
  maMucTieu VARCHAR(20) NOT NULL PRIMARY KEY,
  maQuanLy VARCHAR(20) NOT NULL,
  tenMucTieu NVARCHAR(150) NOT NULL,
  moTaMucTieu NVARCHAR(500) NOT NULL,
  ngayGui DATE NOT NULL,
  trangThaiDanhGia NVARCHAR(50) NOT NULL DEFAULT N'Chờ đánh giá',
  noiDungYeuCau NVARCHAR(500) NULL,
  CONSTRAINT FK_MT_SV FOREIGN KEY(maQuanLy) REFERENCES SinhVien(maQuanLy)
);
GO
CREATE TABLE HoTro (
  maHoTro VARCHAR(20) NOT NULL PRIMARY KEY,
  tenHoTro NVARCHAR(100) NOT NULL,
  loaiHoTro NVARCHAR(50) NOT NULL
);
GO
CREATE TABLE ChiTietHoTro (
  maCTHoTro VARCHAR(20) NOT NULL PRIMARY KEY,
  maQuanLy VARCHAR(20) NOT NULL,
  maHoTro VARCHAR(20) NOT NULL,
  thoiGianHoTro DATETIME2 NOT NULL,
  soTien DECIMAL(12,2) NULL CHECK(soTien>=0),
  CONSTRAINT FK_CTHT_SV FOREIGN KEY(maQuanLy) REFERENCES SinhVien(maQuanLy),
  CONSTRAINT FK_CTHT_HT FOREIGN KEY(maHoTro) REFERENCES HoTro(maHoTro)
);
GO
CREATE TABLE MinhChungHoaDon (
  maMCHD VARCHAR(20) NOT NULL PRIMARY KEY,
  maCTHoTro VARCHAR(20) NOT NULL,
  tenMCHD NVARCHAR(150) NOT NULL,
  linkMCHD NVARCHAR(500) NOT NULL,
  CONSTRAINT FK_MCHD_CTHT FOREIGN KEY(maCTHoTro) REFERENCES ChiTietHoTro(maCTHoTro)
);
GO
CREATE TABLE BaoCao (
  maBaoCao VARCHAR(20) NOT NULL PRIMARY KEY,
  maNguoiDung VARCHAR(20) NOT NULL,
  loaiBaoCao NVARCHAR(50) NOT NULL,
  thoiGianBatDau DATE NOT NULL,
  thoiGianKetThuc DATE NOT NULL,
  ngayLap DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  noiDung NVARCHAR(MAX) NOT NULL,
  ghiChu NVARCHAR(MAX) NULL,
  trangThai NVARCHAR(30) NOT NULL DEFAULT N'Bản nháp',
  CONSTRAINT FK_BC_ND FOREIGN KEY(maNguoiDung) REFERENCES NguoiDung(maNguoiDung),
  CONSTRAINT CK_BC_Date CHECK(thoiGianBatDau<=thoiGianKetThuc)
);
GO
CREATE TABLE TepDinhKem (
  maTep VARCHAR(20) NOT NULL PRIMARY KEY,
  maBaoCao VARCHAR(20) NOT NULL,
  tenTep NVARCHAR(150) NOT NULL,
  linkTep NVARCHAR(500) NOT NULL,
  CONSTRAINT FK_TEP_BC FOREIGN KEY(maBaoCao) REFERENCES BaoCao(maBaoCao)
);
GO
CREATE INDEX IX_SinhVien_HoTen ON SinhVien(hoTen);
CREATE INDEX IX_SinhVien_Phong ON SinhVien(maPhong);
CREATE INDEX IX_LichSu_ThoiGian ON LichSuHoatDong(thoiGian DESC);
CREATE INDEX IX_HoSoDangKy_TrangThai ON HoSoDangKy(trangThaiHoSo);
GO
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.TABLES WHERE TABLE_TYPE='BASE TABLE' ORDER BY TABLE_NAME;
